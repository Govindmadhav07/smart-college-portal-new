
import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'

const API = 'http://localhost:5000/api/fees'
const ACADEMIC_YEAR = '2026-27'

function loadRazorpayScript() {
  return new Promise((resolve) => {
    if (window.Razorpay) return resolve(true)

    const script = document.createElement('script')
    script.src = 'https://checkout.razorpay.com/v1/checkout.js'
    script.onload = () => resolve(true)
    script.onerror = () => resolve(false)
    document.body.appendChild(script)
  })
}

function escapeHTML(value) {
  return String(value ?? '').replace(/[&<>"']/g, (char) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;'
  })[char])
}

function downloadReceipt(fee, payment) {
  if (payment.status !== 'Paid') {
    alert('Receipt sirf successful payment ke liye available hai.')
    return
  }

  const receiptWindow = window.open('', '_blank')

  if (!receiptWindow) {
    alert('Browser mein pop-ups allow karke dobara try karo.')
    return
  }

  const amount = Number(payment.amount || 0).toLocaleString('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  })

  const details = [
    ['Receipt Number', payment.receiptNo || payment.paymentId || 'N/A'],
    ['Student Name', fee.studentName || 'N/A'],
    ['Roll Number', fee.rollNo || 'N/A'],
    ['Academic Year', fee.academicYear || ACADEMIC_YEAR],
    ['Payment Date', payment.paidAt ? new Date(payment.paidAt).toLocaleString('en-IN') : 'N/A'],
    ['Payment Method', payment.method || 'Online'],
    ['Payment ID', payment.paymentId || 'N/A'],
    ['Amount Paid', `₹${amount}`],
    ['Payment Status', 'Paid']
  ]

  receiptWindow.document.write(`
    <!DOCTYPE html>
    <html lang="en">
    <head>
      <meta charset="UTF-8">
      <meta name="viewport" content="width=device-width, initial-scale=1.0">
      <title>College Fee Receipt</title>
      <style>
        body {
          font-family: Arial, sans-serif;
          color: #1f2937;
          background: #f1f5f9;
          padding: 25px;
        }
        .receipt {
          max-width: 700px;
          margin: 20px auto;
          padding: 30px;
          background: white;
          border: 1px solid #ddd;
          border-radius: 10px;
        }
        h1 { text-align: center; color: #1e293b; }
        .subtitle { text-align: center; color: #64748b; }
        .status {
          text-align: center;
          padding: 12px;
          margin: 25px 0;
          background: #dcfce7;
          color: #166534;
          font-weight: bold;
        }
        table { width: 100%; border-collapse: collapse; }
        td { padding: 13px 8px; border-bottom: 1px solid #e5e7eb; }
        td:first-child { font-weight: bold; width: 40%; }
        .print {
          display: block;
          margin: 25px auto 0;
          padding: 12px 22px;
          border: none;
          border-radius: 6px;
          background: #2563eb;
          color: white;
          cursor: pointer;
        }
        @media print {
          body { background: white; padding: 0; }
          .receipt { border: none; }
          .print { display: none; }
        }
      </style>
    </head>
    <body>
      <div class="receipt">
        <h1>COLLEGE FEE RECEIPT</h1>
        <p class="subtitle">Student Fee Payment Acknowledgement</p>
        <div class="status">PAYMENT SUCCESSFUL</div>
        <table>
          ${details.map(([label, value]) =>
            `<tr><td>${escapeHTML(label)}</td><td>${escapeHTML(value)}</td></tr>`
          ).join('')}
        </table>
        <p style="margin-top:25px;color:#64748b;font-size:12px">
          Keep this receipt for your records. This is a receipt generated by the college portal.
        </p>
        <button class="print" onclick="window.print()">Print / Save as PDF</button>
      </div>
    </body>
    </html>
  `)

  receiptWindow.document.close()
}

export default function StudentFees() {
  const [fee, setFee] = useState(null)
  const [loading, setLoading] = useState(true)
  const [paying, setPaying] = useState(false)
  const [amount, setAmount] = useState('')
  const [message, setMessage] = useState('')
  const [error, setError] = useState('')
  

  const token = localStorage.getItem('token')

  async function loadFee() {
    setLoading(true)
    setError('')

    try {
      const response = await fetch(
        `${API}/mine?academicYear=${encodeURIComponent(ACADEMIC_YEAR)}`,
        {
          headers: { Authorization: `Bearer ${token}` }
        }
      )

      const data = await response.json()

      if (!response.ok) {
        throw new Error(data.message || 'Fees load nahi ho paayi.')
      }

      setFee(data.fee || null)
    } catch (err) {
      setError(err.message || 'Server se connect nahi ho paaya.')
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => {
    if (!token) {
      setError('Login session nahi mila. Dobara login karo.')
      setLoading(false)
      return
    }

    loadFee()
  }, [])

  async function payFees(event) {
    event.preventDefault()
    setMessage('')
    setError('')

    const paymentAmount = Number(amount)

    if (!Number.isFinite(paymentAmount) || paymentAmount <= 0) {
      setError('Valid payment amount enter karo.')
      return
    }

    if (paymentAmount > Number(fee?.balance || 0)) {
      setError('Payment amount remaining balance se zyada nahi ho sakta.')
      return
    }

    setPaying(true)

    try {
      const scriptLoaded = await loadRazorpayScript()

      if (!scriptLoaded) {
        throw new Error('Razorpay load nahi hua. Internet check karo.')
      }

      const orderResponse = await fetch(`${API}/create-order`, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${token}`
        },
        body: JSON.stringify({
          amount: paymentAmount,
          academicYear: fee.academicYear || ACADEMIC_YEAR
        })
      })

      const orderData = await orderResponse.json()

      if (!orderResponse.ok) {
        throw new Error(orderData.message || 'Payment order create nahi hua.')
      }

      const checkout = new window.Razorpay({
        key: orderData.keyId,
        amount: orderData.amount,
        currency: orderData.currency || 'INR',
        name: 'College Fee Payment',
        description: `Academic Year ${fee.academicYear || ACADEMIC_YEAR}`,
        order_id: orderData.orderId,
        prefill: {
          name: orderData.studentName || fee.studentName || '',
          email: orderData.studentEmail || ''
        },
        theme: { color: '#2563eb' },

        handler: async function (paymentResponse) {
          try {
            const verifyResponse = await fetch(`${API}/verify-payment`, {
              method: 'POST',
              headers: {
                'Content-Type': 'application/json',
                Authorization: `Bearer ${token}`
              },
              body: JSON.stringify(paymentResponse)
            })

            const verifyData = await verifyResponse.json()

            if (!verifyResponse.ok) {
              throw new Error(verifyData.message || 'Payment verification failed.')
            }

            setMessage(
              `Payment successful! Receipt number: ${verifyData.receiptNo || 'Payment History mein check karo.'}`
            )
            setAmount('')
            await loadFee()
          } catch (err) {
            setError(
              `${err.message} Page refresh karke payment status check karo.`
            )
          } finally {
            setPaying(false)
          }
        },

        modal: {
          ondismiss: () => setPaying(false)
        }
      })

      checkout.on('payment.failed', (response) => {
        setError(response.error?.description || 'Payment unsuccessful.')
        setPaying(false)
      })

      checkout.open()
    } catch (err) {
      setError(err.message || 'Payment start nahi ho paayi.')
      setPaying(false)
    }
  }

  const totalFees = Number(fee?.totalFees || 0)
  const paid = Number(fee?.paid || 0)
  const balance = Number(fee?.balance || 0)
  const payments = fee?.payments || []

  const money = (value) =>
    `₹${Number(value || 0).toLocaleString('en-IN', {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2
    })}`

  const styles = {
    page: {
      maxWidth: '1100px',
      margin: '0 auto',
      padding: '24px',
      fontFamily: 'Arial, sans-serif',
      color: '#1f2937'
    },
    heading: {
      fontSize: '28px',
      marginBottom: '6px',
      color: '#1e293b'
    },
    muted: {
      color: '#64748b',
      marginTop: 0
    },
    cards: {
      display: 'grid',
      gridTemplateColumns: 'repeat(auto-fit, minmax(190px, 1fr))',
      gap: '16px',
      margin: '24px 0'
    },
    card: {
      padding: '20px',
      border: '1px solid #e5e7eb',
      borderRadius: '12px',
      background: '#ffffff',
      color: '#1f2937',
      boxShadow: '0 2px 8px rgba(0,0,0,0.04)'
    },
    label: {
      color: '#64748b',
      fontSize: '14px',
      marginBottom: '10px'
    },
    value: {
      fontSize: '24px',
      fontWeight: 'bold',
      overflowWrap: 'anywhere'
    },
    section: {
      padding: '22px',
      border: '1px solid #e5e7eb',
      borderRadius: '12px',
      marginTop: '22px',
      background: '#ffffff',
      color: '#1f2937'
    },
    sectionHeading: {
      color: '#1e293b',
      marginTop: 0,
      marginBottom: '18px'
    },
    input: {
      width: '100%',
      maxWidth: '350px',
      padding: '12px',
      border: '1px solid #d1d5db',
      borderRadius: '7px',
      fontSize: '16px',
      margin: '10px 0 14px',
      display: 'block',
      background: '#ffffff',
      color: '#1f2937'
    },
    button: {
      background: '#2563eb',
      color: '#ffffff',
      border: 'none',
      padding: '12px 18px',
      borderRadius: '7px',
      cursor: 'pointer',
      fontSize: '15px'
    },
    receiptButton: {
      background: '#15803d',
      color: '#ffffff',
      border: 'none',
      padding: '9px 12px',
      borderRadius: '6px',
      cursor: 'pointer',
      whiteSpace: 'nowrap'
    },
    tableWrap: {
      width: '100%',
      overflowX: 'auto'
    },
    table: {
      width: '100%',
      minWidth: '720px',
      borderCollapse: 'collapse',
      marginTop: '12px'
    },
    cell: {
      padding: '12px 10px',
      borderBottom: '1px solid #e5e7eb',
      textAlign: 'left',
      fontSize: '14px',
      color: '#1f2937'
    },
    tableHeader: {
      padding: '12px 10px',
      background: '#1e3a8a',
      color: '#ffffff',
      textAlign: 'left',
      fontSize: '14px'
    }
  }

  if (loading) {
    return <div style={styles.page}>Loading fee details...</div>
  }

  return (
    <div style={styles.page}>
      <h1 style={styles.heading}>My Fees</h1>
      <p style={styles.muted}>View your fee details and payment history.</p>
      
<Link
  to="/dashboard">
                <button>← Back to Dashboard</button>
</Link>


      {error && (
        <div role="alert" style={{
          padding: '12px',
          background: '#fef2f2',
          color: '#b91c1c',
          borderRadius: '8px',
          marginTop: '15px'
        }}>
          {error}
        </div>
      )}

      {message && (
        <div role="status" style={{
          padding: '12px',
          background: '#f0fdf4',
          color: '#166534',
          borderRadius: '8px',
          marginTop: '15px'
        }}>
          {message}
        </div>
      )}

      {!fee ? (
        <div style={styles.section}>
          <h3 style={styles.sectionHeading}>Fee record not available</h3>
          <p>Your fee details have not been assigned for {ACADEMIC_YEAR}.</p>
          <button style={styles.button} onClick={loadFee}>Refresh</button>
        </div>
      ) : (
        <>
          <div style={styles.section}>
            <h2 style={styles.sectionHeading}>Student Details</h2>
            <p><strong>Name:</strong> {fee.studentName || 'N/A'}</p>
            <p><strong>Roll Number:</strong> {fee.rollNo || 'N/A'}</p>
            <p><strong>Academic Year:</strong> {fee.academicYear || ACADEMIC_YEAR}</p>
            <p><strong>Course:</strong> {fee.course || 'N/A'}</p>
          </div>

          <div style={styles.cards}>
            <div style={styles.card}>
              <div style={styles.label}>Total Fees</div>
              <div style={styles.value}>{money(totalFees)}</div>
            </div>

            <div style={styles.card}>
              <div style={styles.label}>Fees Paid</div>
              <div style={{ ...styles.value, color: '#15803d' }}>
                {money(paid)}
              </div>
            </div>

            <div style={styles.card}>
              <div style={styles.label}>Remaining Balance</div>
              <div style={{ ...styles.value, color: '#b45309' }}>
                {money(balance)}
              </div>
            </div>
          </div>

          <div style={styles.section}>
            <h2 style={styles.sectionHeading}>Pay Fees Online</h2>

            {balance <= 0 ? (
              <p style={{ color: '#15803d', fontWeight: 'bold' }}>
                All fees have been paid.
              </p>
            ) : (
              <form onSubmit={payFees}>
                <label htmlFor="paymentAmount">Enter amount to pay (₹)</label>

                <input
                  id="paymentAmount"
                  type="number"
                  min="1"
                  max={balance}
                  step="0.01"
                  required
                  value={amount}
                  onChange={(event) => setAmount(event.target.value)}
                  placeholder={`Maximum ${balance}`}
                  style={styles.input}
                />

                <button
                  type="submit"
                  disabled={paying}
                  style={{ ...styles.button, opacity: paying ? 0.65 : 1 }}
                >
                  {paying ? 'Processing...' : 'Pay with Razorpay'}
                </button>
              </form>
            )}
          </div>

          <div style={styles.section}>
            <h2 style={styles.sectionHeading}>Payment History</h2>

            {payments.length === 0 ? (
              <p>No payment history available yet.</p>
            ) : (
              <div style={styles.tableWrap}>
                <table style={styles.table}>
                  <thead>
                    <tr>
                      {['Date', 'Amount', 'Method', 'Status', 'Receipt No.', 'Receipt'].map((heading) => (
                        <th key={heading} style={styles.tableHeader}>{heading}</th>
                      ))}
                    </tr>
                  </thead>

                  <tbody>
                    {[...payments].reverse().map((payment, index) => (
                      <tr key={payment._id || payment.paymentId || payment.orderId || index}>
                        <td style={styles.cell}>
                          {payment.paidAt
                            ? new Date(payment.paidAt).toLocaleDateString('en-IN')
                            : '-'}
                        </td>
                        <td style={styles.cell}>{money(payment.amount)}</td>
                        <td style={styles.cell}>{payment.method || 'Online'}</td>
                        <td style={{
                          ...styles.cell,
                          color: payment.status === 'Paid'
                            ? '#15803d'
                            : payment.status === 'Failed'
                              ? '#b91c1c'
                              : '#b45309',
                          fontWeight: 'bold'
                        }}>
                          {payment.status || 'Pending'}
                        </td>
                        <td style={styles.cell}>{payment.receiptNo || '-'}</td>
                        <td style={styles.cell}>
                          {payment.status === 'Paid' ? (
                            <button
                              type="button"
                              style={styles.receiptButton}
                              onClick={() => downloadReceipt(fee, payment)}
                            >
                              Download Receipt
                            </button>
                          ) : '-'}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </>
      )}
    </div>
  )
}
